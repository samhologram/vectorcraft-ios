#!/usr/bin/env bash
# Run the VectorCraft UI tests (smoke, tool / panel / command tours) or the unit tests on ONE simulator that the
# caller has already booted, and export the result's notes and summaries.
#
# Usage: apple/scripts/run-ui-tests.sh <udid> [suite]
#        apple/scripts/run-ui-tests.sh --regen-lists
#   suite (default "smoke"): smoke | unit | tools | panels | commands | tours (tools+panels+commands) | all |
#                            any xcodebuild -only-testing identifier (VectorCraftUITests/ToolTourUITests/testToolsPortrait)
#   Environment: TOUR_LIMIT=n / TOUR_ONLY=id,id are forwarded to the tours (as TEST_RUNNER_*).
# Needs the products from `xcodebuild build-for-testing -scheme VectorCraft -destination 'generic/platform=iOS Simulator'
#   ARCHS=arm64 CODE_SIGNING_ALLOWED=NO -derivedDataPath build/dd-core` (this script never builds and never boots a
#   simulator: the orchestrator owns the simulator lock).
# Output: apple/build/results/<suite>/ (exported attachments, printed below); the .xcresult is deleted after export.
#   Read every *-notes and *-tour-summary text: a green run can be hollow. No screenshots are attached by the tests.
#
# --regen-lists rewrites apple/VectorCraftUITests/TourCatalog.swift (tool groups, panels, desktop menu entries,
#   excluded commands) from the bridge's catalogs (scripts/dump-catalog.sh, crates/tools/src/catalog.rs and
#   bridge/ios-excluded-commands.txt). Run it whenever the catalogs change; needs cargo and python3
#   (DUMP_BIN=<path of a built bridge `dump` example> skips the cargo run).
set -euo pipefail

APPLE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$APPLE_DIR"
export DEVELOPER_DIR="${DEVELOPER_DIR:-/Applications/Xcode.app/Contents/Developer}"

regen_lists() {
  local tmp; tmp="$(mktemp -d)"
  for what in menus panels tools; do
    if [[ -n "${DUMP_BIN:-}" ]]; then "$DUMP_BIN" "$what" > "$tmp/$what.txt"   # a prebuilt bridge `dump` example
    else scripts/dump-catalog.sh "$what" > "$tmp/$what.txt"; fi
  done
  python3 -I - "$tmp" "$APPLE_DIR" <<'PY'
import re, sys, json, os
tmp, apple = sys.argv[1], sys.argv[2]
repo = os.path.dirname(apple)

# --- tool groups: grouping comes from crates/tools/src/catalog.rs, ids are cross-checked with the bridge dump
src = open(os.path.join(repo, "crates/tools/src/catalog.rs")).read()
block = src.split("TOOL_GROUPS: &[&[ToolInfo]] = &[", 1)[1].split("\n];", 1)[0]
groups = []
for m in re.finditer(r'^\s*&\[(.*?)\],\s*$', block, re.S | re.M):
    ids = re.findall(r't\("([^"]+)",\s*"([^"]*)"', m.group(1))
    if ids: groups.append(ids)
dumped = [l.split("\t")[0] for l in open(f"{tmp}/tools.txt").read().splitlines() if l.strip()]
parsed = [i for g in groups for i, _ in g]
if parsed != dumped:
    sys.exit(f"tool list from catalog.rs ({len(parsed)}) differs from the bridge's tool_catalog ({len(dumped)})")

panels = [l.split("\t")[:2] for l in open(f"{tmp}/panels.txt").read().splitlines() if l.strip()]

# --- desktop menu entries
entries = []   # (path, id, params, occurrence, label)
stack = []     # (indent, label) of open submenus
title = None
seen = {}
for line in open(f"{tmp}/menus.txt").read().splitlines():
    if not line.strip(): continue
    if not line.startswith(" "):
        title = line.strip(); stack = []; continue
    indent = (len(line) - len(line.lstrip())) // 2   # 1 = top level of the section
    body = line.strip()
    stack = [s for s in stack if s[0] < indent]
    if body == "---" or body.startswith("(todo)"): continue
    if body.startswith("> "):
        stack.append((indent, body[2:])); continue
    m = re.match(r'^(.*?)\s+\[([A-Za-z0-9_.@-]+)(?: (.*))?\]$', body)
    if not m: continue
    label, cid, params = m.group(1), m.group(2), m.group(3) or "{}"
    occ = seen.get(cid, 0); seen[cid] = occ + 1
    entries.append(([title] + [s[1] for s in stack], cid, params, occ, label))

excluded = {}
p = os.path.join(apple, "bridge/ios-excluded-commands.txt")
if os.path.exists(p):
    for l in open(p).read().splitlines():
        if l.strip() and not l.startswith("#"):
            k, _, reason = l.partition("\t"); excluded[k.strip()] = reason.strip() or "excluded"

# Keep in sync with MenuLayout.hidden (App/EditorCommands.swift): handled by system menus / canvas responder actions.
system_handled = ["file.newDialog", "file.newWithoutDialog", "file.newFromTemplate", "file.open", "file.clearRecent",
    "file.recentFiles", "file.close", "file.closeAll", "file.save", "file.saveAs", "app.quit", "app.home",
    "edit.undo", "edit.redo", "edit.cut", "edit.copy", "edit.paste", "edit.preferences", "edit.keyboardShortcuts"]

def q(s): return json.dumps(s, ensure_ascii=False)
out = ["// GENERATED by `apple/scripts/run-ui-tests.sh --regen-lists` from the bridge catalogs. Do not edit.",
       "// Source of truth: vectorcraft-apple tool_catalog() / panel_catalog() / desktop_menu_layout() and",
       "// bridge/ios-excluded-commands.txt. The UI test target does not link VectorCraftKit, hence a generated list.",
       "", "enum TourCatalog {",
       "    struct Tool { let id: String; let label: String; let group: String; let groupSize: Int }",
       "    struct Panel { let id: String; let label: String }",
       "    struct MenuCommand { let id: String; let label: String; let path: [String]; let paramsJson: String; let occurrence: Int }",
       "", "    /// Every tool in toolbar order; `group` is the group's first tool id (the `toolGroup.<id>` button).",
       "    static let tools: [Tool] = ["]
for g in groups:
    for tid, label in g:
        out.append(f"        Tool(id: {q(tid)}, label: {q(label)}, group: {q(g[0][0])}, groupSize: {len(g)}),")
out += ["    ]", "", "    /// panel_catalog(), in Window-menu order.", "    static let panels: [Panel] = ["]
for pid, label in panels: out.append(f"        Panel(id: {q(pid)}, label: {q(label)}),")
out += ["    ]", "", "    /// Every command entry of the desktop menu bar (todo items and separators dropped), in menu order.",
        "    static let menuCommands: [MenuCommand] = ["]
for path, cid, params, occ, label in entries:
    out.append(f"        MenuCommand(id: {q(cid)}, label: {q(label)}, path: {q(path)}, paramsJson: {q(params)}, occurrence: {occ}),")
out += ["    ]", "", "    /// ios-excluded-commands.txt: id -> reason.", "    static let excluded: [String: String] = ["]
for k, v in sorted(excluded.items()): out.append(f"        {q(k)}: {q(v)},")
if not excluded: out.append("        :")
out += ["    ]", "", "    /// Ids the iOS menus hand to the system (MenuLayout.hidden): not reachable through the overflow menu.",
        "    static let systemHandled: Set<String> = ["]
for k in system_handled: out.append(f"        {q(k)},")
out += ["    ]", "}", ""]
dest = os.path.join(apple, "VectorCraftUITests/TourCatalog.swift")
open(dest, "w").write("\n".join(out))
print(f"wrote {dest}: {sum(len(g) for g in groups)} tools in {len(groups)} groups, {len(panels)} panels, "
      f"{len(entries)} menu entries, {len(excluded)} excluded")
PY
  rm -rf "$tmp"
}

if [[ "${1:-}" == "--regen-lists" ]]; then regen_lists; exit 0; fi
if [[ "${1:-}" == "-h" || "${1:-}" == "--help" || $# -lt 1 ]]; then sed -n '2,19p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit $([[ $# -lt 1 ]] && echo 2 || echo 0); fi

UDID="$1"; SUITE="${2:-smoke}"
DD=build/dd-core; OUT=build/results
mkdir -p "$OUT"
[[ -d "$DD/Build/Products" ]] || { echo "no build products in $DD: run build-for-testing first (see the header)" >&2; exit 1; }

UI=VectorCraftUITests
case "$SUITE" in
  smoke)    ONLY=("$UI/$UI") ;;
  unit)     ONLY=(VectorCraftTests) ;;
  tools)    ONLY=("$UI/ToolTourUITests") ;;
  panels)   ONLY=("$UI/PanelTourUITests") ;;
  commands) ONLY=("$UI/CommandTourUITests") ;;
  tours)    ONLY=("$UI/ToolTourUITests" "$UI/PanelTourUITests" "$UI/CommandTourUITests") ;;
  all)      ONLY=(VectorCraftTests "$UI/$UI" "$UI/ToolTourUITests" "$UI/PanelTourUITests" "$UI/CommandTourUITests") ;;
  *)        ONLY=("$SUITE") ;;
esac
NAME="$(echo "$SUITE" | tr '/:' '--')"
RESULT="$OUT/$NAME.xcresult"; EXPORT="$OUT/$NAME"
rm -rf "$RESULT" "$EXPORT"

ARGS=(); for t in "${ONLY[@]}"; do ARGS+=("-only-testing:$t"); done
[[ -n "${TOUR_LIMIT:-}" ]] && export TEST_RUNNER_TOUR_LIMIT="$TOUR_LIMIT"
[[ -n "${TOUR_ONLY:-}" ]] && export TEST_RUNNER_TOUR_ONLY="$TOUR_ONLY"

STATUS=0
xcodebuild test-without-building -scheme VectorCraft -destination "id=$UDID" -derivedDataPath "$DD" \
  -resultBundlePath "$RESULT" "${ARGS[@]}" > "$OUT/$NAME.log" 2>&1 || { STATUS=1; echo "xcodebuild reported failures (see $OUT/$NAME.log)"; tail -25 "$OUT/$NAME.log"; }

if [[ -d "$RESULT" ]]; then
  xcrun xcresulttool export attachments --path "$RESULT" --output-path "$EXPORT" >/dev/null 2>&1 \
    || echo "warning: could not export attachments from $RESULT" >&2
  # Print every notes / summary attachment (manifest.json maps the exported file names to the attachment names).
  python3 -I - "$EXPORT" <<'PY' || true
import json, os, sys
d = sys.argv[1]
mf = os.path.join(d, "manifest.json")
if not os.path.exists(mf):
    print("no manifest.json in", d); sys.exit(0)
seen = 0
for test in json.load(open(mf)):
    for att in test.get("attachments", []):
        name = att.get("suggestedHumanReadableName") or att.get("name") or ""
        if not any(k in name for k in ("notes", "tour-summary", "palette-ids")): continue
        path = os.path.join(d, att.get("exportedFileName", ""))
        if not os.path.isfile(path): continue
        seen += 1
        print(f"\n===== {test.get('testIdentifier', '')} :: {name} =====")
        print(open(path, errors="replace").read())
print(f"\n({seen} notes/summary attachments)")
PY
  rm -rf "$RESULT"   # attachments are exported; the bundle is large
else
  echo "no result bundle produced (see $OUT/$NAME.log)" >&2; STATUS=1
fi
# Leave nothing installed on the shared simulator (cleanup rule); the caller shuts it down and releases .sim.lock.
xcrun simctl uninstall "$UDID" ca.hologram.vectorcraft 2>/dev/null || true
xcrun simctl uninstall "$UDID" ca.hologram.vectorcraft.uitests.xctrunner 2>/dev/null || true
echo "==> $SUITE done; exported attachments in $APPLE_DIR/$EXPORT (log: $OUT/$NAME.log)"
exit $STATUS
