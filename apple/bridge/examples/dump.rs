//! Prints the catalogs: `cargo run --example dump -- engine|ui|menus|tools|panels|full`.
//! Used by the scripts in `apple/scripts`. Tab separated; `full` is the human-readable catalog-dump.txt.
use std::collections::BTreeMap;
use vectorcraft_apple::{MenuItemInfo, MenuSection};

fn clean(s: &str) -> String {
    s.replace(['\n', '\t'], " ")
}

/// command id -> first menu path it appears at (plain items only), e.g. "File > Export".
fn menu_paths(layout: &[MenuSection]) -> BTreeMap<String, String> {
    fn walk(items: &[MenuItemInfo], path: &mut Vec<String>, out: &mut BTreeMap<String, String>) {
        for it in items {
            match it.kind.as_str() {
                "command" => {
                    out.entry(it.command.clone()).or_insert_with(|| path.join(" > "));
                }
                "submenu" => {
                    path.push(it.label.clone());
                    walk(&it.children, path, out);
                    path.pop();
                }
                _ => {}
            }
        }
    }
    let mut out = BTreeMap::new();
    for s in layout {
        walk(&s.items, &mut vec![s.title.clone()], &mut out);
    }
    out
}

fn print_menu(items: &[MenuItemInfo], depth: usize) {
    for it in items {
        let pad = "  ".repeat(depth);
        match it.kind.as_str() {
            "separator" => println!("{pad}---"),
            "submenu" => {
                println!("{pad}> {}", it.label);
                print_menu(&it.children, depth + 1);
            }
            "todo" => println!("{pad}(todo) {}", it.label),
            _ => {
                let p = if it.params_json == "{}" { String::new() } else { format!(" {}", it.params_json) };
                println!("{pad}{}  [{}{}]", it.label, it.command, p);
            }
        }
    }
}

fn main() {
    let what = std::env::args().nth(1).unwrap_or_default();
    let layout = vectorcraft_apple::desktop_menu_layout();
    match what.as_str() {
        "engine" => {
            for c in vectorcraft_apple::command_catalog() {
                println!("{}\t{}\t{}\t{}", c.id, c.label, c.menu.join(">"), clean(&c.params));
            }
        }
        "ui" => {
            let paths = menu_paths(&layout);
            for c in vectorcraft_apple::ui_command_catalog() {
                println!("{}\t{}\t{}", c.id, c.label, paths.get(&c.id).map(|p| p.replace(" > ", ">")).unwrap_or_default());
            }
        }
        "menus" => {
            for m in &layout {
                println!("{}", m.title);
                print_menu(&m.items, 1);
            }
        }
        "tools" => {
            for g in vectorcraft_apple::tool_catalog() {
                for t in g.tools {
                    println!("{}\t{}\t{}\t{}", t.id, t.label, t.shortcut.unwrap_or_default(), t.icon);
                }
            }
        }
        "panels" => {
            for p in vectorcraft_apple::panel_catalog() {
                println!("{}\t{}\t{}", p.id, p.label, p.menu.join(">"));
            }
        }
        "full" => {
            println!("# VectorCraft bridge catalog dump (generated by `cargo run --example dump -- full`; do not edit)");
            println!("# engine {}", vectorcraft_apple::engine_version());
            println!();
            let engine = vectorcraft_apple::command_catalog();
            println!("## Engine commands ({})", engine.len());
            println!("# id | label | menu | shortcut | query | params");
            for c in &engine {
                println!(
                    "{} | {} | {} | {} | {} | {}",
                    c.id,
                    c.label,
                    c.menu.join(">"),
                    c.shortcut.clone().unwrap_or_default(),
                    if c.is_query { "query" } else { "edit" },
                    clean(&c.params)
                );
            }
            let ui = vectorcraft_apple::ui_command_catalog();
            println!();
            println!("## UI-only desktop commands ({})", ui.len());
            println!("# id | label | shortcut | params");
            for c in &ui {
                println!("{} | {} | {} | {}", c.id, c.label, c.shortcut.clone().unwrap_or_default(), clean(&c.params));
            }
            println!();
            println!("## Tools (toolbar groups)");
            for (n, g) in vectorcraft_apple::tool_catalog().iter().enumerate() {
                for t in &g.tools {
                    println!("group {n} | {} | {} | {} | {}", t.id, t.label, t.shortcut.clone().unwrap_or_default(), t.icon);
                }
            }
            println!();
            println!("## Panels (Window menu)");
            println!("# id | label | menu");
            for p in vectorcraft_apple::panel_catalog() {
                println!("{} | {} | {}", p.id, p.label, p.menu.join(">"));
            }
            println!();
            println!("## Desktop menu layout (label  [command params])");
            for m in &layout {
                println!("{}", m.title);
                print_menu(&m.items, 1);
            }
        }
        _ => eprintln!("usage: dump engine|ui|menus|tools|panels|full"),
    }
}
